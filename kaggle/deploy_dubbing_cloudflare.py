"""
deploy_dubbing_cloudflare.py
============================
Kaggle kernel script — runs on Kaggle's T4 GPU as a HEADLESS SCRIPT
(not an interactive notebook). Push with:

    kaggle kernels push -p . --accelerator NvidiaTeslaT4

Uses the ShadowGPU pattern:
  1. Install deps
  2. Write all pipeline files
  3. Patch IndicF5 model.py
  4. Launch Streamlit on port 8501
  5. Start Cloudflare Quick Tunnel
  6. Broadcast tunnel URL to ntfy.sh channel
  7. Stream ntfy.sh for SHUTDOWN_DUBBING signal (kill switch)

Environment variables read from Kaggle Secrets:
  - GEMINI_API_KEY : Google AI Studio key
  - HF_TOKEN       : HuggingFace read token (IndicF5 gated model)
  - NTFY_CHANNEL   : Your unique ntfy.sh channel name (set this below)

Local usage (after kernel is live):
  curl -s ntfy.sh/YOUR_NTFY_CHANNEL/raw   # Watch for the URL
  curl -d "SHUTDOWN_DUBBING" ntfy.sh/YOUR_NTFY_CHANNEL  # Kill it
"""

