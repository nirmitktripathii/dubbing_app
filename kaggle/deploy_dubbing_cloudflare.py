PATCHED_MODEL = r'''
import sys, os
from datetime import datetime

def debug_log(msg):
    t = datetime.now().strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
    print(f"[{t}] [HF_Model] {msg}", flush=True)

debug_log("model.py loaded (Kaggle-patched version).")
current_dir = os.path.dirname(os.path.abspath(__file__))
sys.path.append(current_dir)

from transformers import PreTrainedModel, PretrainedConfig
import torch, numpy as np, soundfile as sf, io
from pydub import AudioSegment, silence
from huggingface_hub import hf_hub_download
from safetensors.torch import load_file
from f5_tts.infer.utils_infer import infer_process, load_model, load_vocoder, preprocess_ref_audio_text
from f5_tts.model import DiT

class INF5Config(PretrainedConfig):
    model_type = "inf5"
    def __init__(self, ckpt_path="checkpoints/model_best.pt",
                 vocab_path="checkpoints/vocab.txt",
                 speed=1.0, remove_sil=True, **kwargs):
        super().__init__(**kwargs)
        self.ckpt_path = ckpt_path
        self.vocab_path = vocab_path
        self.speed = speed
        self.remove_sil = remove_sil

class INF5Model(PreTrainedModel):
    config_class = INF5Config

    def load_state_dict(self, state_dict, strict=False):
        new_sd = {k.replace("._orig_mod.", "."): v for k, v in state_dict.items()}
        return super().load_state_dict(new_sd, strict=False)

    def __init__(self, config):
        debug_log("INF5Model.__init__ starting...")
        super().__init__(config)
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        debug_log(f"Device: {device}")

        # Step 1: Vocoder on CPU first (avoids meta-tensor OOM)
        debug_log("Loading vocoder on CPU...")
        vocoder = load_vocoder(vocoder_name="vocos", is_local=False, device=torch.device("cpu"))
        if str(device) != "cpu":
            vocoder = vocoder.to(device)
        self.__dict__["vocoder"] = vocoder
        debug_log("Vocoder loaded.")

        # Step 2: Vocab
        vocab_path = hf_hub_download(config.name_or_path, filename="checkpoints/vocab.txt")
        debug_log(f"Vocab: {vocab_path}")

        # Step 3: DiT architecture
        self.ema_model = load_model(
            DiT,
            dict(dim=1024, depth=22, heads=16, ff_mult=2, text_dim=512, conv_layers=4),
            mel_spec_type="vocos", vocab_file=vocab_path, device=device
        )
        debug_log("DiT architecture loaded.")

        # Step 3b: Real weights from model.safetensors
        ckpt_path = hf_hub_download(config.name_or_path, filename="model.safetensors")
        state_dict = load_file(ckpt_path, device=str(device))
        ema_state = {}
        for k, v in state_dict.items():
            if k.startswith("ema_model."):
                nk = k[len("ema_model."):]
                if nk.startswith("_orig_mod."):
                    nk = nk[len("_orig_mod."):]
                nk = nk.replace("._orig_mod.", ".")
                ema_state[nk] = v
        missing, unexpected = self.ema_model.load_state_dict(ema_state, strict=False)
        debug_log(f"Weights loaded. missing={len(missing)}, unexpected={len(unexpected)}")
        debug_log("INF5Model.__init__ complete!")

    def forward(self, text, ref_audio_path, ref_text):
        if not os.path.exists(ref_audio_path):
            raise FileNotFoundError(f"Ref audio not found: {ref_audio_path}")
        ref_audio, ref_text = preprocess_ref_audio_text(ref_audio_path, ref_text)
        self.ema_model.to(self.device)
        self.vocoder.to(self.device)
        audio, sr, _ = infer_process(
            ref_audio, ref_text, text,
            self.ema_model, self.vocoder,
            mel_spec_type="vocos", speed=self.config.speed, device=self.device,
        )
        buf = io.BytesIO()
        sf.write(buf, audio, samplerate=24000, format="WAV")
        buf.seek(0)
        seg = AudioSegment.from_file(buf, format="wav")
        if self.config.remove_sil:
            parts = silence.split_on_silence(seg, min_silence_len=1000, silence_thresh=-50, keep_silence=500)
            seg = sum(parts, AudioSegment.silent(duration=0))
        seg = seg.apply_gain(-20.0 - seg.dBFS)
        return np.array(seg.get_array_of_samples())
'''

