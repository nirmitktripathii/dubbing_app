# ── Step 7: Cloudflare Quick Tunnel ──────────────────────────────────────────
send_log("Step 7/7: Opening Cloudflare Quick Tunnel...")

tunnel_proc = subprocess.Popen(
    ["/usr/local/bin/cloudflared", "tunnel", "--url", "http://localhost:8501"],
    stdout=subprocess.PIPE,
    stderr=subprocess.STDOUT,
    text=True,
)

public_url = ""
for line in tunnel_proc.stdout:
    print(f"  [cloudflared] {line.rstrip()}", flush=True)
    match = re.search(r"https://[a-zA-Z0-9\-]+\.trycloudflare\.com", line)
    if match:
        public_url = match.group(0)
        break

if public_url:
    msg = f"DUBBING APP IS LIVE! Open: {public_url}"
    requests.post(
        f"https://ntfy.sh/{NTFY_CHANNEL}",
        data=msg.encode("utf-8"),
        timeout=10,
    )
    send_log(msg)
else:
    send_log("ERROR: Could not extract Cloudflare URL from tunnel output.")

send_log("All steps complete. Listening for SHUTDOWN_DUBBING signal...")

# ── Kill Switch ───────────────────────────────────────────────────────────────
try:
    response = requests.get(f"https://ntfy.sh/{NTFY_CHANNEL}/raw", stream=True, timeout=None)
    for line in response.iter_lines():
        if line:
            decoded = line.decode("utf-8")
            if "SHUTDOWN_DUBBING" in decoded:
                requests.post(
                    f"https://ntfy.sh/{NTFY_CHANNEL}",
                    data="[DUBBING-GPU]: Kill switch activated! Shutting down.".encode("utf-8"),
                    timeout=10,
                )
                tunnel_proc.terminate()
                streamlit_proc.terminate()
                os._exit(0)
except Exception:
    pass
